import { SignJWT } from 'jose'
import { describe, expect, it } from 'vitest'
import { durationSeconds, hashPassword, issueTokens, tokenMatchesUser, verifyPassword, verifyToken } from '../src/lib/auth'

const user = (over: Partial<Parameters<typeof tokenMatchesUser>[1] & object> = {}) => ({
  id: 'u1',
  email: 'a@example.com',
  role: 'user',
  passwordHash: '$2a$10$abcdefghijklmnopqrstuv',
  isActive: true,
  deletedAt: null,
  ...over,
})

describe('tokens', () => {
  it('issues access and refresh tokens that only verify for their purpose', async () => {
    const pair = await issueTokens(user())
    expect(await verifyToken(pair.accessToken, 'access')).toMatchObject({ sub: 'u1' })
    expect(await verifyToken(pair.accessToken, 'refresh')).toBeNull()
    expect(await verifyToken(pair.refreshToken, 'refresh')).toMatchObject({ sub: 'u1' })
    expect(await verifyToken(pair.refreshToken, 'access')).toBeNull()
    expect(pair.expiresIn).toBe(24 * 3600)
  })

  it('revokes tokens on password change, deactivation and deletion', async () => {
    const { accessToken } = await issueTokens(user())
    const claims = (await verifyToken(accessToken, 'access'))!
    expect(tokenMatchesUser(claims, user())).toBe(true)
    expect(tokenMatchesUser(claims, user({ passwordHash: '$2a$10$different' }))).toBe(false)
    expect(tokenMatchesUser(claims, user({ isActive: false }))).toBe(false)
    expect(tokenMatchesUser(claims, user({ deletedAt: new Date() }))).toBe(false)
    expect(tokenMatchesUser(claims, undefined)).toBe(false)
  })

  it('rejects other algorithms, missing expiry and wrong secrets', async () => {
    const secret = new TextEncoder().encode('test-secret-test-secret-test-secret-1234')
    const noExp = await new SignJWT({ purpose: 'access', credential: 'x' }).setProtectedHeader({ alg: 'HS256' }).setSubject('u1').sign(secret)
    expect(await verifyToken(noExp, 'access')).toBeNull()
    const hs512 = await new SignJWT({ purpose: 'access', credential: 'x' })
      .setProtectedHeader({ alg: 'HS512' })
      .setSubject('u1')
      .setExpirationTime('1h')
      .sign(new TextEncoder().encode('test-secret-test-secret-test-secret-1234'.repeat(2)))
    expect(await verifyToken(hs512, 'access')).toBeNull()
    const expired = await new SignJWT({ purpose: 'access', credential: 'x' })
      .setProtectedHeader({ alg: 'HS256' })
      .setSubject('u1')
      .setExpirationTime(Math.floor(Date.now() / 1000) - 10)
      .sign(secret)
    expect(await verifyToken(expired, 'access')).toBeNull()
    expect(await verifyToken('garbage', 'access')).toBeNull()
  })

  it('parses durations', () => {
    expect(durationSeconds('24h')).toBe(86400)
    expect(durationSeconds('30m')).toBe(1800)
    expect(() => durationSeconds('1w')).toThrow()
  })
})

describe('passwords', () => {
  it('verifies hashes produced by the Go backend ($2a$, cost 10)', async () => {
    // Generated by golang.org/x/crypto/bcrypt for "password123".
    const goHash = '$2a$10$8lpfmDHA1027ib9KZsODB.tOZyoaqMGpXaZDJvMqMvd3MFjvM8QCu'
    expect(await verifyPassword('password123', goHash)).toBe(true)
    expect(await verifyPassword('wrong', goHash)).toBe(false)
  })

  it('round-trips new hashes', async () => {
    const hash = await hashPassword('s3cret-pass')
    expect(hash).toMatch(/^\$2[ab]\$10\$/)
    expect(await verifyPassword('s3cret-pass', hash)).toBe(true)
  })
})
